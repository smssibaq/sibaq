import { describe, it, expect } from 'vitest';
import {
  joinByCodeSchema,
  normalizeRoomCode,
  ROOM_CODE_DEFAULT_LENGTH,
  ROOM_CODE_MIN_LENGTH,
  ROOM_CODE_MAX_LENGTH,
  ROOM_CODE_REGEX,
} from '../modules/invitations/schema';

describe('Room Code Validation & Normalization', () => {
  it('defines correct room code length boundaries matching Supabase', () => {
    expect(ROOM_CODE_DEFAULT_LENGTH).toBe(16);
    expect(ROOM_CODE_MIN_LENGTH).toBe(6);
    expect(ROOM_CODE_MAX_LENGTH).toBe(16);
  });

  it('normalizes room code by trimming whitespace and converting to uppercase', () => {
    expect(normalizeRoomCode('  7a3f8b1c9e2d4f0a  ')).toBe('7A3F8B1C9E2D4F0A');
    expect(normalizeRoomCode('abc123def4567890')).toBe('ABC123DEF4567890');
    expect(normalizeRoomCode('  trf7a9  ')).toBe('TRF7A9');
  });

  it('accepts valid 16-character hexadecimal codes generated by Supabase', () => {
    const valid16Hex = '7A3F8B1C9E2D4F0A';
    const result = joinByCodeSchema.safeParse({ code: valid16Hex });
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.code).toBe(valid16Hex);
    }
  });

  it('accepts and normalizes lowercase 16-character codes with whitespace', () => {
    const input = '   7a3f8b1c9e2d4f0a   ';
    const result = joinByCodeSchema.safeParse({ code: input });
    expect(result.success).toBe(true);
  });

  it('preserves backwards compatibility for 6-character room codes', () => {
    const legacyCode = 'TRF7A9';
    const result = joinByCodeSchema.safeParse({ code: legacyCode });
    expect(result.success).toBe(true);
  });

  it('rejects codes that are shorter than 6 characters with clear message', () => {
    const shortCode = '12345';
    const result = joinByCodeSchema.safeParse({ code: shortCode });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.issues[0].message).toContain('too short');
    }
  });

  it('rejects codes that exceed 16 characters', () => {
    const longCode = '7A3F8B1C9E2D4F0A1B2C'; // 20 chars
    const result = joinByCodeSchema.safeParse({ code: longCode });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.issues[0].message).toContain('cannot exceed 16');
    }
  });

  it('rejects invalid characters (symbols, spaces within code) with clear feedback', () => {
    const invalidSymbol = '7A3F-8B1C_9E2D4F';
    const result = joinByCodeSchema.safeParse({ code: invalidSymbol });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.error.issues[0].message).toContain('can only contain letters and numbers');
    }
  });

  it('rejects empty input with clear prompt', () => {
    const result = joinByCodeSchema.safeParse({ code: '' });
    expect(result.success).toBe(false);
  });

  it('regex validates alphanumeric characters', () => {
    expect(ROOM_CODE_REGEX.test('7A3F8B1C9E2D4F0A')).toBe(true);
    expect(ROOM_CODE_REGEX.test('7a3f8b1c9e2d4f0a')).toBe(true);
    expect(ROOM_CODE_REGEX.test('TRF7A9')).toBe(true);
    expect(ROOM_CODE_REGEX.test('7A3F@8B1C')).toBe(false);
    expect(ROOM_CODE_REGEX.test('7A3F 8B1C')).toBe(false);
  });
});
